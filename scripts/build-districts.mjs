// District boundaries for the map's "Districts" mode, from the Census Bureau's 2024 cartographic
// boundary files (1:500k): congressional districts of the 119th Congress, state senate (upper)
// and state house (lower) districts. Each layer is projected exactly like the base map
// (Albers USA, scale 1300), simplified for phones and written as its own file, which the app
// loads only when that layer is chosen:
//   data/generated/districts-cd.js, districts-sldu.js, districts-sldl.js
// Run with: npm run build:districts   (add --refresh to re-download)
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import AdmZip from "adm-zip";
import * as shapefile from "shapefile";
import * as d3 from "d3";
import { geoProject } from "d3-geo-projection";
import { topology } from "topojson-server";
import { presimplify, simplify, quantile, filter, filterWeight } from "topojson-simplify";
import { quantize } from "topojson-client";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RAW = path.join(ROOT, "scripts/raw/districts");
fs.mkdirSync(RAW, { recursive: true });
const UA = `Mozilla/5.0 (research script; contact ${process.env.DATA_CONTACT_EMAIL ?? "data@example.org"})`;
const REFRESH = process.argv.includes("--refresh");
await import(path.join(ROOT, "data/states-meta.js"));
const stateOf = Object.fromEntries(globalThis.STATES_META.map(([fips, abbr]) => [fips, abbr]));
const projection = d3.geoAlbersUsa().scale(1300).translate([487.5, 305]);

const LAYERS = [
  // `keep`: share of boundary points kept after simplification (smaller districts need more).
  { id: "cd", file: "cb_2024_us_cd119_500k", label: "U.S. House", code: (p) => p.CD119FP, keep: 0.03 },
  { id: "sldu", file: "cb_2024_us_sldu_500k", label: "State Senate", code: (p) => p.SLDUST, keep: 0.03 },
  { id: "sldl", file: "cb_2024_us_sldl_500k", label: "State House", code: (p) => p.SLDLST, keep: 0.03 },
];

for (const layer of LAYERS) {
  const zip = path.join(RAW, `${layer.file}.zip`);
  if (REFRESH || !fs.existsSync(zip)) execFileSync("curl", ["-sSfL", "-m", "600", "-A", UA, "-o", zip, `https://www2.census.gov/geo/tiger/GENZ2024/shp/${layer.file}.zip`]);
  const dir = path.join(RAW, layer.file);
  if (!fs.existsSync(path.join(dir, `${layer.file}.shp`))) new AdmZip(zip).extractAllTo(dir, true);
  const src = await shapefile.read(path.join(dir, `${layer.file}.shp`), path.join(dir, `${layer.file}.dbf`));
  const features = [];
  for (const f of src.features) {
    const st = stateOf[f.properties.STATEFP];
    if (!st) continue; // territories
    const code = layer.code(f.properties);
    if (!code || /^Z+$/.test(code)) continue; // "ZZZ" = area not in any district (water, etc.)
    const projected = geoProject(f, projection);
    if (!projected.geometry) continue;
    features.push({ type: "Feature", id: `${st}-${code}`, properties: { st, code, name: (f.properties.NAMELSAD ?? "").replace(/\s+\(.*\)$/, "") }, geometry: projected.geometry });
  }
  // Planar topology in map pixels; drop detail below what a phone can show at high zoom.
  let topo = topology({ d: { type: "FeatureCollection", features } });
  topo = presimplify(topo);
  const minWeight = quantile(topo, 1 - layer.keep);
  topo = filter(simplify(topo, minWeight), filterWeight(topo, minWeight)); // also drops slivers too small to see
  topo = quantize(topo, 1e4); // integer, delta-encoded coordinates: ~0.1 map px, plenty at any zoom
  const out = path.join(ROOT, `data/generated/districts-${layer.id}.js`);
  fs.writeFileSync(out, `// Generated by scripts/build-districts.mjs from the Census Bureau's ${layer.file} — do not edit by hand.\n(globalThis.DISTRICTS ??= {}).${layer.id} = ${JSON.stringify(topo)};\n`);
  console.log(`${layer.label}: ${features.length} districts, ${(fs.statSync(out).size / 1024 / 1024).toFixed(2)} MB`);
}
