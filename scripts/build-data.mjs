// Downloads public election / officeholder data and compiles it into the compact
// browser-ready files in data/generated/. Run with: npm run build:data
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as d3 from "d3";
import * as topojson from "topojson-client";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RAW = path.join(ROOT, "scripts/raw");
const OUT = path.join(ROOT, "data/generated");
fs.mkdirSync(RAW, { recursive: true });
fs.mkdirSync(OUT, { recursive: true });

await import(path.join(ROOT, "data/states-meta.js"));
const META = globalThis.STATES_META;
const byName = Object.fromEntries(META.map(([f, a, n]) => [n, a]));
const byFips = Object.fromEntries(META.map(([f, a]) => [f, a]));

const COUNTY_REPO = "https://raw.githubusercontent.com/tonmcg/US_County_Level_Election_Results_08-24/master/";
const SOURCES = {
  "pres2024.csv": COUNTY_REPO + "2024_US_County_Level_Presidential_Results.csv",
  "pres2020.csv": COUNTY_REPO + "2020_US_County_Level_Presidential_Results.csv",
  "pres0816.csv": COUNTY_REPO + "US_County_Level_Presidential_Results_08-16.csv",
  "house.csv": "https://raw.githubusercontent.com/fivethirtyeight/election-results/main/election_results_house.csv",
  "legislators-current.json": "https://raw.githubusercontent.com/unitedstates/congress-legislators/gh-pages/legislators-current.json",
  "cities.csv": "https://raw.githubusercontent.com/plotly/datasets/master/us-cities-top-1k.csv",
};

async function raw(name) {
  const file = path.join(RAW, name);
  if (!fs.existsSync(file) || process.argv.includes("--refresh")) {
    const res = await fetch(SOURCES[name]);
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return fs.readFileSync(file, "utf8");
}

const write = (name, globalName, value) =>
  fs.writeFileSync(path.join(OUT, name), `// Generated by scripts/build-data.mjs — do not edit by hand.\nglobalThis.${globalName} = ${JSON.stringify(value)};\n`);

// ---------- Map ----------
const atlasPath = path.join(ROOT, "node_modules/us-atlas/counties-albers-10m.json");
const atlas = JSON.parse(fs.readFileSync(atlasPath, "utf8"));
write("atlas.js", "US_ATLAS", atlas);

// ---------- County presidential results (2016/2020/2024) ----------
// Each result is stored as [rep, dem, other, total] vote counts.
const counties = {};
const ensure = (fips, name, st) => (counties[fips] ??= { n: name, st });
for (const [year, file] of [[24, "pres2024.csv"], [20, "pres2020.csv"]]) {
  for (const r of d3.csvParse(await raw(file))) {
    const st = byName[r.state_name];
    if (!st) continue;
    const fips = r.county_fips.padStart(5, "0");
    const rep = +r.votes_gop, dem = +r.votes_dem, tot = +r.total_votes;
    ensure(fips, r.county_name, st)["v" + year] = [rep, dem, Math.max(0, tot - rep - dem), tot];
  }
}
for (const r of d3.csvParse(await raw("pres0816.csv"))) {
  const fips = r.fips_code.padStart(5, "0");
  const st = byFips[fips.slice(0, 2)];
  if (!st || !r.total_2016) continue;
  ensure(fips, r.county, st).v16 = [+r.gop_2016, +r.dem_2016, +r.oth_2016, +r.total_2016];
}

// State and national totals are summed from every reporting unit for each year.
const states = {};
const nation = {};
for (const c of Object.values(counties)) {
  for (const y of ["v24", "v20", "v16"]) {
    if (!c[y]) continue;
    const s = (states[c.st] ??= {});
    s[y] = (s[y] ?? [0, 0, 0, 0]).map((v, i) => v + c[y][i]);
    nation[y] = (nation[y] ?? [0, 0, 0, 0]).map((v, i) => v + c[y][i]);
  }
}
// Keep only units that exist on the map (Alaska house districts / CT planning regions are
// not map counties; those map counties fall back to state/older-year data in the browser).
const mapCounties = new Map(atlas.objects.counties.geometries.map((g) => [g.id, g.properties.name]));
const countyOut = {};
for (const [fips, name] of mapCounties) {
  const st = byFips[fips.slice(0, 2)];
  if (!st) continue;
  const c = counties[fips] ?? { n: name, st };
  countyOut[fips] = { n: name, st, ...(c.v24 && { v24: c.v24 }), ...(c.v20 && { v20: c.v20 }), ...(c.v16 && { v16: c.v16 }) };
}
write("elections.js", "ELECTIONS", { counties: countyOut, states, nation });

// ---------- 2024 U.S. House results by district ----------
const houseRows = d3.csvParse(await raw("house.csv")).filter(
  (r) => r.cycle === "2024" && (r.stage === "general" || (r.state_abbrev === "LA" && r.stage === "jungle primary")) && r.office_name === "U.S. House" && r.special === "false" &&
    (r.ranked_choice_round === "" || r.ranked_choice_round === "1") && byFips[META.find((m) => m[1] === r.state_abbrev)?.[0]]
);
const seats = Object.fromEntries(META.map((m) => [m[1], m[3]]));
// At-large seats are keyed as district 0 (matching the Congress roster).
const races = d3.group(houseRows, (r) => `${r.state_abbrev}-${seats[r.state_abbrev] === 1 ? 0 : +(r.office_seat_name.match(/\d+/)?.[0] ?? 0)}`);
const house = {};
for (const [key, rows] of races) {
  // Candidates on several fusion lines (NY) are merged by politician; party = first major-party line.
  const cands = d3.rollup(rows, (rs) => ({
    name: rs[0].candidate_name,
    votes: d3.sum(rs, (r) => +r.votes || 0),
    party: rs.some((r) => r.ballot_party === "DEM") ? "D" : rs.some((r) => r.ballot_party === "REP") ? "R"
      : rs.some((r) => r.ballot_party === "IND") ? "I" : "O",
    winner: rs.some((r) => r.winner === "true"),
    unopposed: rs.some((r) => r.unopposed === "true"),
  }), (r) => r.candidate_name ? r.politician_id : "blank-" + r.ballot_party);
  const list = [...cands.values()];
  const total = d3.sum(list, (c) => c.votes);
  const sum = (p) => d3.sum(list.filter((c) => c.party === p), (c) => c.votes);
  const w = list.find((c) => c.winner) ?? d3.greatest(list, (c) => c.votes);
  house[key] = { R: sum("R"), D: sum("D"), I: sum("I"), O: sum("O"), total, winner: w?.name, wp: w?.party, unopposed: list.length === 1 || !!w?.unopposed };
}
write("house2024.js", "HOUSE24", house);

// ---------- Current members of Congress ----------
const legislators = JSON.parse(await raw("legislators-current.json"));
const yearsBetween = (a, b) => (new Date(b) - new Date(a)) / 3.15576e10;
const TODAY = new Date().toISOString().slice(0, 10);
const congress = legislators.map((l) => {
  const t = l.terms.at(-1);
  const served = (type) => d3.sum(l.terms.filter((x) => x.type === type), (x) => yearsBetween(x.start, x.end < TODAY ? x.end : TODAY));
  const houseStates = [...new Set(l.terms.filter((x) => x.type === "rep").map((x) => `${x.state}-${x.district}`))];
  return {
    id: l.id.bioguide,
    name: l.name.official_full ?? `${l.name.first} ${l.name.last}`,
    last: l.name.last,
    party: t.party === "Democrat" ? "D" : t.party === "Republican" ? "R" : "I",
    caucus: t.caucus === "Democrat" ? "D" : t.caucus === "Republican" ? "R" : undefined,
    type: t.type, state: t.state, district: t.district, cls: t.class,
    start: t.start, end: t.end, born: l.bio?.birthday, gender: l.bio?.gender,
    firstElected: l.terms[0].start,
    houseYears: +served("rep").toFixed(1), senateYears: +served("sen").toFixed(1),
    priorDistricts: t.type === "sen" ? houseStates : undefined,
    url: t.url, wiki: l.id.wikipedia, leadership: l.leadership_roles?.filter((r) => !r.end).map((r) => r.title),
  };
}).filter((m) => byFips[META.find((x) => x[1] === m.state)?.[0]]);
write("congress.js", "CONGRESS", congress);

// ---------- Cities (1,000 largest), each assigned to its county by point-in-polygon ----------
const geo = JSON.parse(fs.readFileSync(path.join(ROOT, "node_modules/us-atlas/counties-10m.json"), "utf8"));
const countyFeatures = topojson.feature(geo, geo.objects.counties).features;
const cityRows = d3.csvParse(await raw("cities.csv"));
const cities = [];
for (const r of cityRows) {
  const st = byName[r.State];
  if (!st) continue;
  const pt = [+r.lon, +r.lat];
  const fipsPrefix = META.find((m) => m[1] === st)[0];
  const county = countyFeatures.find((f) => f.id.startsWith(fipsPrefix) && d3.geoContains(f, pt));
  // Coastal points that fall just outside the simplified outlines snap to the nearest county.
  const id = county?.id ?? d3.least(countyFeatures.filter((f) => f.id.startsWith(fipsPrefix)), (f) => d3.geoDistance(d3.geoCentroid(f), pt)).id;
  cities.push([r.City, st, +r.Population, +pt[0].toFixed(4), +pt[1].toFixed(4), id]);
}
cities.sort((a, b) => b[2] - a[2]);
write("cities.js", "CITIES", cities);

console.log(`counties ${Object.keys(countyOut).length}, house races ${Object.keys(house).length}, members ${congress.length}, cities ${cities.length} (no county: ${cities.filter((c) => !c[5]).length})`);
