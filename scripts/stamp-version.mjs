// Writes data/generated/version.js: a content hash of the app code and every data file the site loads.
// The page polls this file every 30 minutes and reloads itself when the hash changes.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// App code is included so an installed app also updates itself after code changes.
const FILES = ["index.html", "manifest.webmanifest", "sw.js", "css/style.css", "js/app.js", "js/stats.js", "js/model.js", "js/pwa.js", "js/refresh.js",
  "data/states-meta.js", "data/leaders.js", "data/state-indicators.js", "data/polling.js",
  ...fs.readdirSync(path.join(ROOT, "data/generated")).filter((f) => f.endsWith(".js") && f !== "version.js").sort().map((f) => `data/generated/${f}`)];
const hash = crypto.createHash("sha256");
for (const f of FILES) hash.update(fs.readFileSync(path.join(ROOT, f)));
const version = hash.digest("hex").slice(0, 16);
const file = path.join(ROOT, "data/generated/version.js");
const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").match(/version: "(\w+)"/)?.[1] : null;
if (current === version) console.log(`data version unchanged (${version})`);
else {
  fs.writeFileSync(file, `// Generated by scripts/stamp-version.mjs — do not edit by hand.\nglobalThis.DATA_VERSION = { version: "${version}", updated: "${new Date().toISOString()}" };\n`);
  console.log(`data version ${current ?? "(none)"} -> ${version}`);
}
